#!/bin/sh
# Generates tasks/BOARD.md from the task files.
#   scripts/board.sh > tasks/BOARD.md
#   scripts/board.sh --next-id
set -eu

cd "$(dirname "$0")/../tasks"

field() { # field <file> <name>
	awk -v k="$2" 'NR==1 && $0=="---" {fm=1; next} fm && $0=="---" {exit} fm && index($0, k": ")==1 {sub(k": ", ""); print; exit}' "$1"
}

if [ "${1:-}" = "--next-id" ]; then
	last=$(ls open doing done 2>/dev/null | grep -o '^T-[0-9]\{4\}' | sort | tail -n 1 | cut -c3-)
	printf 'T-%04d\n' $(($(expr "${last:-0}" + 0) + 1))
	exit 0
fi

echo "# Board"
echo
echo "Generated by \`scripts/board.sh\`. Do not edit by hand."
for status in doing open done; do
	echo
	case $status in
		doing) echo "## Doing" ;;
		open) echo "## Open" ;;
		done) echo "## Done" ;;
	esac
	echo
	files=$(ls "$status"/T-*.md 2>/dev/null || true)
	if [ -z "$files" ]; then
		echo "Nothing here."
		continue
	fi
	echo "| Id | Title | Type | Priority |"
	echo "| --- | --- | --- | --- |"
	for f in $files; do
		echo "| [$(field "$f" id)]($f) | $(field "$f" title) | $(field "$f" type) | $(field "$f" priority) |"
	done
done
